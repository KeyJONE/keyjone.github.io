"""Generate the paper index and jemdoc detail sources from publications.json."""
import json
import re
from html import escape
from hashlib import sha256
from pathlib import Path

ROOT=Path(__file__).resolve().parent
SITE=ROOT/'site'


def text(value):
    """Escape prose without changing hyphens or Unicode scientific text."""
    return re.sub(r'([\\/*+\[\]#{}_\$%~])',r'\\\1',str(value))


def authors(names):
    if len(names)<2:
        return names[0] if names else ''
    if len(names)==2:
        return ' and '.join(names)
    return ', '.join(names[:-1])+', and '+names[-1]


def link(url,label):
    return '['+url.replace('#','\\#')+' '+text(label)+']'


def linked_text(value,links):
    """Link selected phrases while escaping the surrounding prose."""
    if not links:
        return text(value)
    targets={item['label']:item['url'] for item in links}
    labels=sorted(targets,key=len,reverse=True)
    pattern=r'(?<!\w)('+'|'.join(re.escape(label) for label in labels)+r')(?!\w)'
    return ''.join(link(targets[piece],piece) if piece in targets else text(piece)
                   for piece in re.split(pattern,value))


def citation(paper):
    if paper.get('citation_override'):
        return text(paper['citation_override'])
    value='/'+text(paper['journal'])+'/'
    volume=str(paper.get('volume') or '')
    issue=str(paper.get('issue') or '')
    pages=re.sub(r'\s*[–—-]\s*',' - ',str(paper.get('pages') or ''))
    if volume:
        value+=', '+text(volume)
        if issue:
            value+='('+text(issue)+')'
        if pages:
            value+=':'+text(pages)
    elif pages:
        value+=', '+text(pages)
    value+=', '+str(paper['citation_year'])+'.'
    if paper.get('publication_type'):
        value+=' '+text(paper['publication_type'])+'.'
    return value


def abstract_content(paper):
    if paper.get('abstract_kind') in ('omitted-by-owner','not-applicable'):
        return []
    content=paper.get('abstract_latex') or paper.get('abstract_text') or ''
    if not content:
        return ['Abstract will be added here.','']
    inline_links=paper.get('abstract_links',[])
    result=['== Summary',''] if paper.get('abstract_kind')=='summary' else []
    for paragraph in content.strip().split('\n\n'):
        if paper.get('abstract_latex'):
            # Only explicitly reviewed LaTeX fragments bypass prose escaping.
            pieces=re.split(r'(\$[^$]+\$)',paragraph)
            result.append(''.join(piece if piece.startswith('$') else linked_text(piece,inline_links) for piece in pieces))
        else:
            result.append(linked_text(paragraph,inline_links))
        result.append('')
    return result


def generate():
    dataset=SITE/'publications.json'
    if not dataset.exists():
        return
    papers=json.loads(dataset.read_text(encoding='utf-8'))
    if len({p['slug'] for p in papers})!=len(papers):
        raise ValueError('Paper slugs must be unique.')
    detail_dir=SITE/'papers'
    detail_dir.mkdir(exist_ok=True)
    css_version=sha256((SITE/'custom.css').read_bytes()).hexdigest()[:12]
    index=[
        '# jemdoc: menu{MENU}{publications.html}, addcss{custom.css?v='+css_version+'}',
        '# Generated by generate_papers.py; edit site/publications.json.',
        '= ZHANG, Qi -- Papers',
        '[https://feg.um.edu.mo/cee/ Department of Civil and Environmental Engineering], [https://www.um.edu.mo/ University of Macau]',
        '',
        'Papers are listed below by year of submission before they are published, or year of publication.',
        '',
    ]
    for year in sorted({p['group_year'] for p in papers},reverse=True):
        index.extend(['== '+str(year),''])
        for p in (p for p in papers if p['group_year']==year):
            title=(link('papers/'+p['slug']+'.html',p['title'])
                   if p.get('detail_page',True) else text(p['title']))
            index.append(': {'+title+'} '+text(authors(p['authors'])))
        index.append('')
    (SITE/'publications.jemdoc').write_text('\n'.join(index).rstrip()+'\n',encoding='utf-8',newline='\n')
    for p in papers:
        if not p.get('detail_page',True):
            continue
        lines=[
            '# jemdoc: menu{../MENU}{publications.html}{../}, addcss{../custom.css?v='+css_version+'}',
            '# Generated by generate_papers.py; edit site/publications.json.',
            '= '+text(p['title']),
            '/'+text(authors(p['authors']))+'/',
            '',
        ]
        if p.get('chinese_title'):
            lines.extend([text(p['chinese_title'])+'\\n'+text(p['chinese_authors']),''])
        lines.extend([citation(p),''])
        if p.get('equal_contributors'):
            lines.extend([text(authors(p['equal_contributors'])+' contributed equally to this work.'),''])
        if p.get('manuscript_url'):
            lines.append('- '+link(p['manuscript_url'],'Manuscript'))
        for extra in p.get('extra_links',[]):
            lines.append('- '+link(extra['url'],extra['label']))
        lines.append('')
        lines.extend(abstract_content(p))
        if p.get('corrections'):
            correction=p['corrections']
            lines.extend(['== '+text(correction['heading']),''])
            for paragraph in correction['text'].split('\n\n'):
                pieces=re.split(r'(\$[^$]+\$)',paragraph)
                rendered=''.join(piece if piece.startswith('$') else text(piece) for piece in pieces)
                lines.append('- '+rendered)
            lines.append('')
            if correction.get('image'):
                figure=correction['image']
                src=escape(figure['src'],quote=True)
                alt=escape(figure['alt'],quote=True)
                caption=escape(figure['caption'])
                lines.extend([
                    '~~~','{}{raw}',
                    '<figure class="correction-figure">',
                    f'<a href="{src}" target="_blank" rel="noopener noreferrer"><img src="{src}" alt="{alt}"></a>',
                    f'<figcaption>{caption}</figcaption>',
                    '</figure>','~~~','',
                ])
        (detail_dir/(p['slug']+'.jemdoc')).write_text('\n'.join(lines).rstrip()+'\n',encoding='utf-8',newline='\n')


if __name__=='__main__':
    generate()
